/**
 * Downscale the six venture UI plates and write content-hashed WebP files.
 *
 * Sources are the 1600×3600 PNGs. They ship from git history, not from `public/`.
 * Restore one with:
 *   git show <commit>:public/textures/ventures/<slug>.png > public/textures/ventures/<slug>.png
 * Then run `npm run optimize:textures`. The script deletes the PNGs after a
 * successful write so the Next bundle only contains the WebP plates.
 *
 * sharp is a devDependency. Nothing here is imported by the page.
 */
import { createHash } from "node:crypto";
import { readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = process.cwd();
const directory = path.join(root, "public/textures/ventures");
const manifestPath = path.join(root, "src/data/ventureTextures.ts");
const width = 1024;
const height = 2304;
const startQuality = 82;
const byteBudget = 500 * 1024;
const slugs = ["mikham", "battery-store", "trader-bot", "honarmarket", "yadaki-yar", "sandoq-yar"];

function hexChannel(value) {
  return Math.max(0, Math.min(255, Math.round(value))).toString(16).padStart(2, "0");
}

async function sourcePath(slug) {
  const png = path.join(directory, `${slug}.png`);
  try {
    await readFile(png);
    return png;
  } catch {
    throw new Error(
      `Missing ${path.relative(root, png)}. Restore the 1600×3600 PNG from git history, then rerun.`,
    );
  }
}

async function resized(slug) {
  const file = await sourcePath(slug);
  const input = sharp(file).rotate();
  const meta = await input.metadata();
  const pipeline = sharp(file)
    .rotate()
    .resize(width, height, { fit: "fill", kernel: "lanczos3" });
  const stats = await pipeline.clone().stats();
  const channels = stats.channels;
  const color = `#${hexChannel(channels[0]?.mean ?? 0)}${hexChannel(channels[1]?.mean ?? 0)}${hexChannel(channels[2]?.mean ?? 0)}`;
  const alpha = channels[3];
  const keepAlpha = Boolean(alpha && alpha.min < 255);
  return { slug, meta, color, keepAlpha, pipeline };
}

async function encodeAll(plates, quality) {
  const encoded = [];
  for (const plate of plates) {
    let image = plate.pipeline.clone();
    if (!plate.keepAlpha) image = image.removeAlpha();
    const buffer = await image.webp({ quality, effort: 6, smartSubsample: true }).toBuffer();
    encoded.push({ ...plate, buffer });
  }
  const bytes = encoded.reduce((sum, plate) => sum + plate.buffer.length, 0);
  return { encoded, bytes, quality };
}

const plates = [];
for (const slug of slugs) plates.push(await resized(slug));

let chosen = await encodeAll(plates, startQuality);
while (chosen.bytes > byteBudget && chosen.quality > 60) {
  chosen = await encodeAll(plates, chosen.quality - 2);
}

if (chosen.bytes > byteBudget) {
  throw new Error(
    `Venture textures are ${chosen.bytes} bytes at quality ${chosen.quality}, above the ${byteBudget} byte budget.`,
  );
}

const existing = await readdir(directory);
for (const name of existing) {
  if (/^[a-z0-9-]+-[0-9a-f]{8}\.webp$/.test(name) || slugs.some((slug) => name === `${slug}.png`)) {
    await rm(path.join(directory, name));
  }
}

const records = [];
for (const plate of chosen.encoded) {
  const hash = createHash("sha256").update(plate.buffer).digest("hex").slice(0, 8);
  const filename = `${plate.slug}-${hash}.webp`;
  await writeFile(path.join(directory, filename), plate.buffer);
  records.push({
    slug: plate.slug,
    src: `/textures/ventures/${filename}`,
    color: plate.color,
    bytes: plate.buffer.length,
    sourceWidth: plate.meta.width ?? 0,
    sourceHeight: plate.meta.height ?? 0,
    keepAlpha: plate.keepAlpha,
  });
  console.log(
    `${filename} ${plate.buffer.length} bytes  source ${plate.meta.width}x${plate.meta.height}  color ${plate.color}  alpha ${plate.keepAlpha ? "kept" : "flat"}`,
  );
}

const body = records
  .map((record) => {
    const key = /^[A-Za-z_][A-Za-z0-9_]*$/.test(record.slug) ? record.slug : JSON.stringify(record.slug);
    return `  ${key}: { src: ${JSON.stringify(record.src)}, color: ${JSON.stringify(record.color)}, width: ${width}, height: ${height} },`;
  })
  .join("\n");

const manifest = `/**
 * Venture UI plates. Generated by \`npm run optimize:textures\`.
 * Filenames are the first 8 hex chars of the SHA-256 of the WebP bytes.
 */
export const VENTURE_TEXTURES = {
${body}
} as const;

export type VentureTextureId = keyof typeof VENTURE_TEXTURES;
`;

await writeFile(manifestPath, manifest);
console.log(
  `total ${chosen.bytes} bytes at quality ${chosen.quality} (budget ${byteBudget}). Wrote ${path.relative(root, manifestPath)}.`,
);
